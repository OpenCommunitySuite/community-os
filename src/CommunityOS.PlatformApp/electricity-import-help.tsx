import { useRef } from 'react';

function ImportGuideContent() {
  return <>
    <p>Перевірте пакет накопичувальних показань для вже зареєстрованих установок електроенергії. Перегляд файлу та підтвердження його застосування — окремі дії.</p>
    <h4>Умови та права</h4>
    <p>Для попереднього перегляду потрібне читання електроенергії; для застосування — чинне право визнання показань і підстава. Перевірте вибрану громаду. Довідка не надає дозволів.</p>
    <h4>Порядок дій</h4>
    <ol>
      <li>В «Історія установок» перевірте потрібний прилад і скопіюйте «Ідентифікатор установки». Це UUID установки, а не точки, ділянки чи позначення приладу.</li>
      <li>Збережіть CSV у UTF-8 із комами, без лапок, одним записом на рядок і точним заголовком <code>installation_id,measured_on,channel,value_kwh</code>. Дата — yyyy-MM-dd; регістр — total, day або night відповідно до приладу. Значення — початкове накопичувальне, з десятковою крапкою й до трьох дробових знаків, без множення на коефіцієнт. Межі: 128 КіБ і 500 записів.</li>
      <li>Оберіть «Файл показань», натисніть «Переглянути CSV» та звірте кожний номер рядка, установку, дату, регістр, значення і результат. Стан «Готове до перевірки під час застосування» ще не є визнаним показанням.</li>
      <li>За наявності дозволу окремо натисніть «Підтвердити й застосувати CSV». Надсилається той самий файл із перевіркою відповідності попередньому перегляду. Перевірте «Результат застосування CSV», потім історію показань потрібної установки.</li>
    </ol>
    <h4>Що зміниться</h4>
    <p>Попередній перегляд не визнає показань. Застосування перевіряє актуальні дані й права для кожного рядка та може мати частковий результат: уже визнані рядки залишаються, навіть якщо наступні відхилено або доступ відкликано. Повтор того самого показання повертає попередній запис. Коефіцієнт використовується в оцінці споживання; фінансове нарахування імпорт не проводить.</p>
    <h4>Як виправити</h4>
    <p>Виправте помилкові рядки вихідного файлу та перегляньте його знову. Вибір іншого файлу скидає попередній перегляд і звіт. Інше значення на вже зайняту дату й регістр не виправляє визнаний запис, а створює конфлікт. Після втрати зв’язку звірте історію і построчний результат перед повтором.</p>
    <h4>Типові труднощі</h4>
    <p>Перевірте заголовок, кодування, кількість полів, розмір, UUID установки, дату в її межах і регістр. Майбутні дати, конфлікт із сусідами й непідтримуваний регістр відхиляються. Якщо файл змінився, виконайте новий перегляд. Без права застосування читач може перевірити файл і передати його уповноваженому оператору.</p>
  </>;
}

