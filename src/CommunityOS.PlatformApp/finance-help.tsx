type Topic = keyof typeof topics;
const OpenGuide = createContext<(() => void) | undefined>(undefined);

function HelpContent({ topic }: { topic: Topic }) {
  const text = topics[topic];
  return <>
    <p>{text.purpose}</p>
    <h4>Умови та права</h4><p>{text.access}</p>
    <h4>Порядок дій</h4><ol>{text.steps.map(step => <li key={step}>{step}</li>)}</ol>
    <h4>Що зміниться</h4><p>{text.effect}</p>
    <h4>Як виправити</h4><p>{text.correction}</p>
    <h4>Типові труднощі</h4><p>{text.errors}</p>
  </>;
}

export function FinanceContextHelp({ topic }: { topic: Topic }) {
  const openGuide = useContext(OpenGuide);
  return <details lang="uk">
    <summary>Довідка: {topics[topic].title}</summary>
    <HelpContent topic={topic} />
    {openGuide && <button type="button" onClick={openGuide}>Посібник: кошториси та витрати</button>}
  </details>;
}

export function FinanceHelp({ children }: { children: ReactNode }) {
  const dialog = useRef<HTMLDialogElement>(null);
  const open = () => dialog.current?.showModal();
  return <OpenGuide.Provider value={open}>
    <p><button type="button" onClick={open}>Посібник: кошториси та витрати</button></p>
    {children}
    <dialog ref={dialog} aria-labelledby="finance-guide-title" lang="uk"
      style={{ maxWidth: '52rem', width: 'calc(100% - 4rem)', maxHeight: '80vh', overflowY: 'auto' }}>
      <form method="dialog"><button autoFocus>Закрити посібник</button></form>
      <h2 id="finance-guide-title">Посібник бухгалтера: кошториси та витрати</h2>
      <p>Для читачів фінансів і уповноважених операторів. Оберіть розділ відповідно до своєї дії. Довідка не надає дозволів на виконання операцій.</p>
      <nav aria-label="Розділи посібника"><ul>
        {(Object.keys(topics) as Topic[]).map(topic => <li key={topic}>
          <a href={'#finance-guide-' + topic}>{topics[topic].title}</a>
        </li>)}
      </ul></nav>
      {(Object.keys(topics) as Topic[]).map(topic => <section key={topic} id={'finance-guide-' + topic}>
        <h3>{topics[topic].title}</h3><HelpContent topic={topic} />
      </section>)}
    </dialog>
  </OpenGuide.Provider>;
}
